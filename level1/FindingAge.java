public class FindingAge{
	public static void main(String[] args){
		
	String name="Harry";
	
	int birthYear=2000;
	
	int currentYear=2024;
	
	// Calculate the current age by subtracting birthYear from currentYear
	int currentAge=currentYear-birthYear;
	
	System.out.println(name+"'s age in 2024 is "+currentAge);
	}
	
}
